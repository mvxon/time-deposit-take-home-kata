-- Table and column names are the ones from the requirements (timeDeposits, withdrawals, planType, timeDepositId) in PostgreSQL's snake_case convention.
-- time_deposits.version is a technical column for optimistic locking, so concurrent balance updates cannot silently overwrite each other.
-- Money columns are limited to 15 significant digits: the legacy TimeDeposit keeps the balance as Double, which round-trips exactly only up to 15 digits.
create table time_deposits
(
    id        integer generated by default as identity primary key,
    plan_type varchar(32)    not null,
    days      integer        not null,
    balance   numeric(15, 2) not null,
    version   integer        not null default 0
);

create table withdrawals
(
    id              integer generated by default as identity primary key,
    time_deposit_id integer        not null references time_deposits (id),
    amount          numeric(15, 2) not null,
    date            date           not null
);

create index idx_withdrawals_time_deposit_id on withdrawals (time_deposit_id);
